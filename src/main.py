def add_numbers(a, b):
    """Функція для додавання двох чисел."""
    return a + b

def multiply_numbers(a, b):
    """Функція для множення двох чисел."""
    result=a*b
    return result

def is_even(number):
  """Перевіряє парність числа"""
  if number%2==0:
    return True
  else:
    return False